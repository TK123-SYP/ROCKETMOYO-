
import streamlit as st
import pandas as pd
import os

from reportlab.lib.pagesizes import A4
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer
)
from reportlab.lib.styles import getSampleStyleSheet
from io import BytesIO



def generate_player_report(
    player_name,
    total_matches,
    total_at_bats,
    total_hits,
    total_strikeouts,
    batting_average,
    strikeout_rate
):
    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4
    )

    styles = getSampleStyleSheet()
    story = []

    story.append(
        Paragraph(
            "ROCKETMOYO - PLAYER PERFORMANCE REPORT",
            styles["Title"]
        )
    )

    story.append(Spacer(1, 20))

    story.append(
        Paragraph(
            f"Player Name: {player_name}",
            styles["Heading2"]
        )
    )

    story.append(Spacer(1, 12))

    report_details = [
        f"Matches Played: {int(total_matches)}",
        f"Total At-bats: {int(total_at_bats)}",
        f"Total Hits: {int(total_hits)}",
        f"Total Strikeouts: {int(total_strikeouts)}",
        f"Batting Average: {batting_average:.3f}",
        f"Strikeout Rate: {strikeout_rate:.1f}%"
    ]

    for detail in report_details:
        story.append(
            Paragraph(detail, styles["Normal"])
        )
        story.append(Spacer(1, 8))

    story.append(Spacer(1, 15))

    story.append(
        Paragraph(
            "Performance Analysis",
            styles["Heading2"]
        )
    )

    if total_at_bats < 10:
        analysis = (
            "Insufficient batting data for a reliable assessment. "
            "More match statistics are recommended."
        )
    else:
        concerns = []

        if batting_average < 0.200:
            concerns.append(
                "Possible batting consistency weakness."
            )

        if strikeout_rate >= 30:
            concerns.append(
                "Possible difficulty making contact with the ball."
            )

        if concerns:
            analysis = " ".join(concerns)
        else:
            analysis = (
                "No major batting concerns identified "
                "by the current indicators."
            )

    story.append(
        Paragraph(analysis, styles["Normal"])
    )

    story.append(Spacer(1, 15))

    story.append(
        Paragraph(
            "Generated by ROCKETMOYO Baseball Analytics",
            styles["Italic"]
        )
    )

    def add_footer(canvas, doc):
        canvas.saveState()

        canvas.setFont("Helvetica", 8)

        canvas.drawCentredString(
            A4[0] / 2,
            25,
            "© 2026 ROCKETMOYO. All Rights Reserved."
        )

        canvas.drawRightString(
            A4[0] - 40,
            25,
            f"Page {doc.page}"
        )

        canvas.restoreState()

    document.build(
        story,
        onFirstPage=add_footer,
        onLaterPages=add_footer
    )

    buffer.seek(0)

    return buffer.getvalue()

st.title("📄 ROCKETMOYO Player Performance Reports")

st.write(
    "Generate individual baseball performance reports "
    "using saved player match statistics."
)

HISTORY_FILE = "rocketmoyo_history.csv"

if os.path.exists(HISTORY_FILE):

    history_df = pd.read_csv(HISTORY_FILE)

    if not history_df.empty and "Player" in history_df.columns:

        players = sorted(
            history_df["Player"].dropna().unique()
        )

        if players:

            selected_player = st.selectbox(
                "Select a player",
                players
            )

            player_df = history_df[
                history_df["Player"] == selected_player
            ]

            st.subheader("👤 Player Information")
            st.write("Player Name:", selected_player)

            st.subheader("📊 Player Match History")

            st.dataframe(
                player_df,
                use_container_width=True
            )

            st.subheader("📈 Player Statistics")

            total_matches = pd.to_numeric(
                player_df["Matches"], errors="coerce"
            ).fillna(0).sum()

            total_at_bats = pd.to_numeric(
                player_df["At-bats"], errors="coerce"
            ).fillna(0).sum()

            total_hits = pd.to_numeric(
                player_df["Hits"], errors="coerce"
            ).fillna(0).sum()

            total_strikeouts = pd.to_numeric(
                player_df["Strikeouts"], errors="coerce"
            ).fillna(0).sum()

            batting_average = (
                total_hits / total_at_bats
                if total_at_bats > 0 else 0
            )

            strikeout_rate = (
                total_strikeouts / total_at_bats * 100
                if total_at_bats > 0 else 0
            )

            col1, col2, col3 = st.columns(3)

            col1.metric("Matches", int(total_matches))
            col2.metric("At-bats", int(total_at_bats))
            col3.metric("Hits", int(total_hits))

            col4, col5 = st.columns(2)

            col4.metric(
                "Batting Average",
                f"{batting_average:.3f}"
            )

            col5.metric(
                "Strikeout Rate",
                f"{strikeout_rate:.1f}%"
            )
            
            st.subheader("🔍 Weakness Detective")

            if total_at_bats < 10:
                st.info(
                    "Not enough batting data for reliable analysis. "
                    "Collect more match statistics."
                )

            else:
                if batting_average < 0.200:
                    st.warning(
                        "Possible weakness: Batting consistency."
                    )
                    st.write(
                        "Training suggestion: Practise tee hitting, "
                        "soft toss and controlled batting."
                    )

                if strikeout_rate >= 30:
                    st.warning(
                        "Possible weakness: Making contact with the ball."
                    )
                    st.write(
                        "Training suggestion: Practise pitch recognition, "
                        "timing and contact drills."
                    )

                if batting_average >= 0.200 and strikeout_rate < 30:
                    st.success(
                        "No major batting concerns identified "
                        "by the current indicators."
                    )
            
            st.subheader("📥 Download Player Report")

            pdf_report = generate_player_report(
                selected_player,
                total_matches,
                total_at_bats,
                total_hits,
                total_strikeouts,
                batting_average,
                strikeout_rate
            )

            st.download_button(
                label="Download PDF Report",
                data=pdf_report,
                file_name=f"{selected_player}_Performance_Report.pdf",
                mime="application/pdf"
            )


        else:
            st.info("No player names found in saved records.")

    else:
        st.info("No player records found.")

else:
    st.info(
        "No saved match history found. "
        "Save player match results in Manual Player Analysis first."
    )
